#!/usr/bin/env bash
# OpenKIS container entrypoint.
#  1. installs / upgrades the code in the web root volume from the image copy
#     (/usr/src/openkis), keeping everything the framework generated at run
#     time (misc/, .htaccess, sections created from the admin area, ...)
#  2. writes extra/openkis_config.local.php from the environment
#  3. creates the api_keys.local.js files from the examples / environment
#  4. waits for the database and starts the install wizard on a fresh volume,
#     then applies the regional database updates not applied yet
set -euo pipefail

WEBROOT=/var/www/html
SRC=/usr/src/openkis
say() { echo "[openkis] $*"; }

: "${OPENKIS_DB_HOST:=db}"
: "${OPENKIS_DB_NAME:=openkis}"
: "${OPENKIS_DB_USER:=openkis}"
: "${OPENKIS_DB_PASSWORD:=}"
: "${OPENKIS_CUSTOM:=}"
: "${OPENKIS_MCP_APIKEY:=}"
: "${OPENKIS_MCP_USER:=admin}"
: "${OPENKIS_MCP_READONLY:=0}"
: "${OPENKIS_APIKEY_GROUPS:=}"
: "${OPENKIS_MCP_WRITE_GROUP:=}"
: "${OPENKIS_DB_WAIT:=60}"
: "${OPENKIS_DB_INDEXES:=1}"
: "${OPENKIS_DB_INDEXES_INTERVAL:=3600}"
: "${OPENKIS_DISPLAY_ERRORS:=off}"
: "${OPENKIS_HOME_SECTION:=}"
: "${OPENKIS_ENABLE_PROXY:=0}"
: "${OPENKIS_TRUSTED_PROXIES:=docker}"
: "${OPENKIS_VALIDATOR_RULES_OFF:=}"

# php single-quoted string literal
phpq() { printf "'%s'" "$(printf '%s' "$1" | sed -e "s/\\\\/\\\\\\\\/g" -e "s/'/\\\\'/g")"; }
jsq() { phpq "$1"; }

# --- 1. code -----------------------------------------------------------------
IMAGE_VERSION=$(cat "$SRC/.openkis-image-version" 2>/dev/null || echo unknown)
INSTALLED_VERSION=$(cat "$WEBROOT/.openkis-image-version" 2>/dev/null || echo none)
if [ "$IMAGE_VERSION" != "$INSTALLED_VERSION" ]; then
    say "installing code version $IMAGE_VERSION (volume had: $INSTALLED_VERSION)"
    # no --delete: files created by the framework or the admin stay in place
    rsync -a --chown=www-data:www-data \
        --exclude '/misc/' \
        --exclude '/extra/openkis_config.local.php' \
        --exclude '/config.vars.local.php' \
        --exclude '/bs_map/conf/api_keys.local.js' \
        --exclude '/themes/api_keys.local.js' \
        "$SRC/" "$WEBROOT/"
    # stale section settings removed from the code: finis reads only
    # default.xml.php, but the old copies stay in the volume (no --delete)
    for s in art_categorie art_tipologie bibliography fauna login reports springs; do
        if [ -f "$WEBROOT/sections/$s/default.xml.php" ]; then
            rm -f "$WEBROOT/sections/$s/default.xml"
        fi
    done
fi

# --- 2. configuration ----------------------------------------------------------
CONF="$WEBROOT/extra/openkis_config.local.php"
MARKER="generated by the openkis container entrypoint"
if [ ! -f "$CONF" ] || grep -q "$MARKER" "$CONF"; then
    say "writing extra/openkis_config.local.php from the environment"
    {
        echo "<?php"
        echo "// $MARKER: edit the .env file, not this file."
        echo "// Remove this line to manage the file by hand (it will then be left untouched)."
        echo "global \$_FN;"
        echo "\$_FN['default_database_driver'] = 'mysql';"
        echo "\$_FN['xmetadb_mysqlhost'] = $(phpq "$OPENKIS_DB_HOST");"
        echo "\$_FN['xmetadb_mysqldatabase'] = $(phpq "$OPENKIS_DB_NAME");"
        echo "\$_FN['xmetadb_mysqlusername'] = $(phpq "$OPENKIS_DB_USER");"
        echo "\$_FN['xmetadb_mysqlpassword'] = $(phpq "$OPENKIS_DB_PASSWORD");"
        echo "\$_FN['openkis_custom'] = $(phpq "$OPENKIS_CUSTOM");"
        if [ -n "$OPENKIS_MCP_APIKEY" ]; then
            echo "\$_FN['openkis_mcp_apikey'] = $(phpq "$OPENKIS_MCP_APIKEY");"
            echo "\$_FN['openkis_mcp_user'] = $(phpq "$OPENKIS_MCP_USER");"
            echo "\$_FN['openkis_mcp_readonly'] = $(( OPENKIS_MCP_READONLY ? 1 : 0 ));"
        fi
        # personal API keys: empty keeps the defaults of extra/openkis_config.inc.php
        # (mcp_users may use a key, mcp_write may use the write tools; admins always can)
        if [ -n "$OPENKIS_APIKEY_GROUPS" ]; then
            echo "\$_FN['apikey_groups'] = $(phpq "$OPENKIS_APIKEY_GROUPS");"
        fi
        # record validator: rules switched off, overriding the region's choice
        if [ -n "$OPENKIS_VALIDATOR_RULES_OFF" ]; then
            echo "\$_FN['openkis_validator_rules_off'] = $(phpq "$OPENKIS_VALIDATOR_RULES_OFF");"
        fi
        if [ -n "$OPENKIS_MCP_WRITE_GROUP" ]; then
            echo "\$_FN['openkis_mcp_write_group'] = $(phpq "$OPENKIS_MCP_WRITE_GROUP");"
        fi
        echo "if (!empty(\$_FN['openkis_custom']))"
        echo "{"
        echo "    FN_IncludeScript(\"extra/openkis/custom/{\$_FN['openkis_custom']}/{\$_FN['openkis_custom']}.php\");"
        echo "}"
    } > "$CONF"
    chown www-data:www-data "$CONF"
    chmod 640 "$CONF"
else
    say "extra/openkis_config.local.php is managed by hand, left untouched"
fi
# finis framework settings, read before the OpenKIS config. display_errors is
# "on" by default in finis: PHP warnings would end up inside KML/JSON exports.
{
    echo "<?php"
    echo "// generated by the openkis container entrypoint (OPENKIS_DISPLAY_ERRORS, OPENKIS_HOME_SECTION)"
    echo "global \$_FN;"
    echo "\$_FN['display_errors'] = $(phpq "$OPENKIS_DISPLAY_ERRORS");"
    # landing page; empty = the "home section" chosen in the control center
    echo "\$_FN['home_section_force'] = $(phpq "$OPENKIS_HOME_SECTION");"
} > "$WEBROOT/config.vars.local.php"
chown www-data:www-data "$WEBROOT/config.vars.local.php"

if [ -n "$OPENKIS_CUSTOM" ] && [ ! -f "$WEBROOT/extra/openkis/custom/$OPENKIS_CUSTOM/$OPENKIS_CUSTOM.php" ]; then
    say "WARNING: OPENKIS_CUSTOM=$OPENKIS_CUSTOM but extra/openkis/custom/$OPENKIS_CUSTOM/ does not exist"
fi

if [ -n "$OPENKIS_HOME_SECTION" ] && [ ! -d "$WEBROOT/sections/$OPENKIS_HOME_SECTION" ] \
   && [ ! -d "$WEBROOT/finis/src/sections/$OPENKIS_HOME_SECTION" ]; then
    say "WARNING: OPENKIS_HOME_SECTION=$OPENKIS_HOME_SECTION but sections/$OPENKIS_HOME_SECTION/ does not exist"
fi

# openkis_proxy.php forwards any URL from the server (SSRF). Only the
# Lombardia map layers use it (IGM WMS), so it is off unless asked for.
if [ "$OPENKIS_ENABLE_PROXY" = 1 ]; then
    rm -f /etc/apache2/conf-enabled/openkis-proxy.conf
    say "WARNING: openkis_proxy.php enabled (open HTTP proxy for anyone who can reach the site)"
else
    printf '<LocationMatch "^/+openkis_proxy\\.php">\n    Require all denied\n</LocationMatch>\n' \
        > /etc/apache2/conf-enabled/openkis-proxy.conf
fi

# Client address behind a reverse proxy (Caddy, nginx, a load balancer). The
# proxy is the one connecting to Apache, so without this every visitor has the
# proxy's address, and the login lockout (per username and address) blocks a
# username for everyone. mod_remoteip takes the client from X-Forwarded-For,
# but only when the connection comes from a trusted proxy: the header of any
# other client is ignored, since anyone can send it.
# OPENKIS_TRUSTED_PROXIES: addresses or CIDR ranges, comma or space separated.
# "docker" = the other containers on the networks of this container (the
# bundled Caddy); "none" = off.

# The networks of this container, from the kernel routing table, without
# their gateway: when Docker forwards a published port through its userland
# proxy, every outside visitor arrives from the gateway, and trusting it would
# let anyone choose their address. A proxy on the host is added by address.
docker_subnets() {
    local iface dest gw flags ref use metric mask rest m bits net g l
    local -A gateway=()
    while read -r iface dest gw rest; do
        [ "$dest" = 00000000 ] && [ "$gw" != 00000000 ] && gateway[$iface]=$gw
    done < /proc/net/route
    ip4() { printf '%d.%d.%d.%d' $(($1 >> 24 & 255)) $(($1 >> 16 & 255)) $(($1 >> 8 & 255)) $(($1 & 255)); }
    le() { echo $((0x${1:6:2} << 24 | 0x${1:4:2} << 16 | 0x${1:2:2} << 8 | 0x${1:0:2})); }
    while read -r iface dest gw flags ref use metric mask rest; do
        [ "$iface" = Iface ] || [ "$iface" = lo ] && continue
        [ "$dest" = 00000000 ] || [ "$gw" != 00000000 ] && continue
        m=$(le "$mask"); bits=0
        while [ "$m" -gt 0 ]; do bits=$((bits + (m & 1))); m=$((m >> 1)); done
        net=$(le "$dest")
        g=${gateway[$iface]:-}
        if [ -z "$g" ] || [ "$bits" -ge 32 ]; then
            echo "$(ip4 "$net")/$bits"
            continue
        fi
        g=$(le "$g")
        # the subnet minus the gateway: the sibling block at each length
        for ((l = bits + 1; l <= 32; l++)); do
            m=$(( (0xFFFFFFFF << (32 - l)) & 0xFFFFFFFF ))
            echo "$(ip4 $(( (g ^ (1 << (32 - l))) & m )))/$l"
        done
    done < /proc/net/route
}
REMOTEIP_CONF=/etc/apache2/conf-enabled/openkis-remoteip.conf
proxies=""
for p in $(printf '%s' "$OPENKIS_TRUSTED_PROXIES" | tr ',' ' '); do
    case "$p" in
        none) proxies=""; break ;;
        docker) proxies="$proxies $(docker_subnets | tr '\n' ' ')" ;;
        *[!0-9A-Fa-f:./]*) say "WARNING: OPENKIS_TRUSTED_PROXIES: '$p' is not an address or CIDR range, ignored" ;;
        *) proxies="$proxies $p" ;;
    esac
done
proxies=$(echo $proxies)
if [ -n "$proxies" ]; then
    printf 'RemoteIPHeader X-Forwarded-For\nRemoteIPInternalProxy %s\n' "$proxies" > "$REMOTEIP_CONF"
    say "client address taken from X-Forwarded-For when the request comes from: $proxies"
else
    rm -f "$REMOTEIP_CONF"
fi

# --- 3. map api keys -----------------------------------------------------------
# Regenerated on every start when a key is given in the environment,
# otherwise created once from the example and then left alone.
if [ -n "${THUNDERFOREST_API_KEY:-}${MAPTILER_API_KEY:-}${ALGOLIA_DOCSEARCH_API_KEY:-}" ] \
   || [ ! -f "$WEBROOT/bs_map/conf/api_keys.local.js" ]; then
    cat > "$WEBROOT/bs_map/conf/api_keys.local.js" <<EOF
// generated by the openkis container entrypoint from the environment
var API_KEYS = {
    THUNDERFOREST: $(jsq "${THUNDERFOREST_API_KEY:-}"),
    MAPTILER: $(jsq "${MAPTILER_API_KEY:-}"),
    ALGOLIA_DOCSEARCH: $(jsq "${ALGOLIA_DOCSEARCH_API_KEY:-}")
};
EOF
fi
if [ -n "${ALGOLIA_DOCSEARCH_API_KEY:-}" ] || [ ! -f "$WEBROOT/themes/api_keys.local.js" ]; then
    cat > "$WEBROOT/themes/api_keys.local.js" <<EOF
// generated by the openkis container entrypoint from the environment
var THEME_API_KEYS = {
    ALGOLIA_DOCSEARCH: $(jsq "${ALGOLIA_DOCSEARCH_API_KEY:-}")
};
EOF
fi

# --- 4. database + first install -----------------------------------------------
say "waiting for MySQL at $OPENKIS_DB_HOST (up to ${OPENKIS_DB_WAIT}s)"
for i in $(seq 1 "$OPENKIS_DB_WAIT"); do
    if mariadb-admin ping -h "$OPENKIS_DB_HOST" -u "$OPENKIS_DB_USER" --password="$OPENKIS_DB_PASSWORD" --skip-ssl --silent 2>/dev/null; then
        say "database is up"
        break
    fi
    [ "$i" = "$OPENKIS_DB_WAIT" ] && say "WARNING: database not reachable, starting anyway"
    sleep 1
done

db_sql() {
    mariadb -h "$OPENKIS_DB_HOST" -u "$OPENKIS_DB_USER" --password="$OPENKIS_DB_PASSWORD" \
        --skip-ssl -N "$OPENKIS_DB_NAME" "$@"
}

# a database that already has its users (a database image with the site's
# data, see db-image/README.md, or a restored dump) needs no setup wizard: the
# framework writes misc/ from it on the first request
if [ ! -d "$WEBROOT/misc/fndatabase" ]; then
    mkdir -p "$WEBROOT/misc"
    if [ "$(db_sql -e "SELECT COUNT(*) > 0 FROM fn_users" 2>/dev/null)" = "1" ]; then
        say "new web volume on a database that has its users: no setup wizard"
    else
        touch "$WEBROOT/misc/firstinstall"
        say "fresh installation: open the site to run the setup wizard"
    fi
fi

# --- 4b. regional database updates --------------------------------------------------
# extra/openkis/custom/<OPENKIS_CUSTOM>/updates/*.sql bring an existing regional
# database (one migrated from the old site, or restored from a backup) in line
# with the code: settings, permissions, renamed columns. Each file runs once, in
# name order, before Apache starts; the table openkis_db_updates records which
# ones the database has (and backup.sh dumps it with the rest, so a restored
# backup keeps its own state). A failed file stops the sequence and is retried
# at the next start.
# A database created empty (new installation, or its volume deleted) gets its
# tables from the code itself, already current: the files present in this image
# are recorded as "baseline" without running them, and only later files will run.
UPDATES_DIR="$SRC/extra/openkis/custom/$OPENKIS_CUSTOM/updates"
if [ -n "$OPENKIS_CUSTOM" ] && [ -d "$UPDATES_DIR" ]; then
    ntables=$(db_sql -e "SELECT COUNT(*) FROM information_schema.tables
                         WHERE table_schema = DATABASE()" 2>/dev/null || echo error)
    nsections=$(db_sql -e "SELECT COUNT(*) FROM information_schema.tables
                           WHERE table_schema = DATABASE() AND table_name = 'fn_sections'" 2>/dev/null || echo error)
    if [ "$ntables" = "0" ] || [ "$nsections" = "1" ]; then
        db_sql -e "CREATE TABLE IF NOT EXISTS openkis_db_updates (
                       name VARCHAR(190) NOT NULL PRIMARY KEY,
                       applied DATETIME NOT NULL,
                       how VARCHAR(16) NOT NULL DEFAULT 'applied') ENGINE=InnoDB" \
            || say "WARNING: cannot create the table openkis_db_updates"
        db_sql -e "ALTER TABLE openkis_db_updates
                       ADD COLUMN IF NOT EXISTS how VARCHAR(16) NOT NULL DEFAULT 'applied'" 2>/dev/null || true
    fi
    for f in "$UPDATES_DIR"/*.sql; do
        [ -f "$f" ] || continue
        n=$(basename "$f")
        case "$n" in *[!A-Za-z0-9._-]*) say "WARNING: database update $n skipped: bad file name"; continue ;; esac
        if [ "$ntables" = "0" ]; then
            db_sql -e "INSERT IGNORE INTO openkis_db_updates (name, applied, how) VALUES ('$n', NOW(), 'baseline')" \
                || say "WARNING: database update $n not recorded as baseline"
            continue
        fi
        [ "$nsections" = "1" ] || break
        [ "$(db_sql -e "SELECT COUNT(*) FROM openkis_db_updates WHERE name = '$n'" 2>/dev/null)" = "0" ] || continue
        if db_sql < "$f" 2>/tmp/openkis-update.err; then
            db_sql -e "INSERT INTO openkis_db_updates (name, applied, how) VALUES ('$n', NOW(), 'applied')" \
                || say "WARNING: database update $n applied but not recorded"
            say "database update $n applied"
        else
            say "WARNING: database update $n failed: $(tr '\n' ' ' < /tmp/openkis-update.err)"
            break
        fi
    done
    [ "$ntables" = "0" ] && say "empty database: the regional updates of this image are recorded as baseline"
fi

# --- 5. database indexes ----------------------------------------------------------
# sql/openkis_indexes.sql adds the secondary indexes (see INDEXES.md). It is
# idempotent and skips tables that don't exist yet; OpenKIS creates tables on
# first use, so it runs now and then again every OPENKIS_DB_INDEXES_INTERVAL
# seconds (0 = only at start), in the background so Apache is not delayed.
INDEXES_SQL="$SRC/sql/openkis_indexes.sql"
count_indexes() {
    db_sql -e "SELECT COUNT(DISTINCT table_name, index_name) FROM information_schema.statistics
               WHERE table_schema = DATABASE() AND index_name LIKE 'okx\\_%'" 2>/dev/null || echo 0
}
if [ "$OPENKIS_DB_INDEXES" = "1" ] && [ -f "$INDEXES_SQL" ]; then
    (
        first=1
        while :; do
            before=$(count_indexes)
            if db_sql < "$INDEXES_SQL" 2>/tmp/openkis-indexes.err; then
                after=$(count_indexes)
                if [ "$after" != "$before" ] || [ "$first" = 1 ]; then
                    say "database indexes: $after in place ($((after - before)) added)"
                fi
                first=0
            else
                say "WARNING: database index script failed: $(tr '\n' ' ' < /tmp/openkis-indexes.err)"
            fi
            [ "$OPENKIS_DB_INDEXES_INTERVAL" -gt 0 ] 2>/dev/null || break
            sleep "$OPENKIS_DB_INDEXES_INTERVAL"
        done
    ) &
fi

echo "$IMAGE_VERSION" > "$WEBROOT/.openkis-image-version"
chown www-data:www-data "$WEBROOT" "$WEBROOT/misc" "$WEBROOT/misc/firstinstall" \
    "$WEBROOT/.openkis-image-version" "$WEBROOT/bs_map/conf/api_keys.local.js" \
    "$WEBROOT/themes/api_keys.local.js" 2>/dev/null || true

# a pid file left by the previous run (docker restart, host reboot) makes
# apache2ctl exit with "httpd (pid N) already running" when N is now another
# process of this container, and the container restarts forever
rm -f "${APACHE_PID_FILE:-/var/run/apache2/apache2.pid}"

exec "$@"
